-- mod-companion-mount — the talents and the kinds of mounts.
--
-- GENERATED from the client's DBC files (Talent.dbc, Spell.dbc, CreatureModelData.dbc) by the
-- author's tooling. The trees are the hunter pets': DPS = Ferocity, Tank = Tenacity, Heal =
-- Cunning with its blows replaced by care (90001-90003). Each tree ends with the KEY talent
-- (90010-90012), whose spell depends on the mount's kind.
--
-- `use`: 0 passive aura on the mount, 1 cast on its victim, 2 on itself in combat, 3 on itself
-- under half health, 4 on its master in combat, 5 on its master under 80 % health, 6 not used.
-- `cooldown`: milliseconds between two casts by the AI, 0 for the spell's own cooldown.
--
-- Idempotent: the file may be replayed.

CREATE TABLE IF NOT EXISTS `mod_companion_mount_talent` (
  `id` INT UNSIGNED NOT NULL,
  `tree` TINYINT UNSIGNED NOT NULL COMMENT '0 DPS, 1 Tank, 2 Heal',
  `tier` TINYINT UNSIGNED NOT NULL,
  `col` TINYINT UNSIGNED NOT NULL,
  `spell_1` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '0: the key spell of the mount kind',
  `spell_2` INT UNSIGNED NOT NULL DEFAULT 0,
  `spell_3` INT UNSIGNED NOT NULL DEFAULT 0,
  `use` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `cooldown` INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='CompanionMount: the talents';

CREATE TABLE IF NOT EXISTS `mod_companion_mount_kind` (
  `mount_spell` INT UNSIGNED NOT NULL,
  `kind` TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (`mount_spell`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='CompanionMount: the kind of each mount';

CREATE TABLE IF NOT EXISTS `mod_companion_mount_kind_spell` (
  `kind` TINYINT UNSIGNED NOT NULL,
  `key_spell` INT UNSIGNED NOT NULL COMMENT 'first rank',
  `use` TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT 'as mod_companion_mount_talent.use',
  `comment` VARCHAR(32) NOT NULL DEFAULT '',
  PRIMARY KEY (`kind`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='CompanionMount: the key spell of each kind';

